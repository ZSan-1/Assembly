TITLE pr8c.asm
DOSSEG
.MODEL SMALL
.STACK 0100h
.DATA
	str1 db "Numbers: $"
	str2 db 0AH, 0DH, "Program Ends$"
.CODE
	MOV AX, @DATA 
	MOV DS, AX

	MOV AH, 09H
	MOV DX, OFFSET str1
	INT 21H

	MOV AH, 02H
	MOV CX, 0AH
	MOV DL, 30H
	A: INT 21H
	INC DL
	LOOP A

	MOV AH, 09H
	MOV DX, OFFSET str2
	INT 21H

	MOV AX, 4C00h
	INT 21h
END
