TITLE pr13.asm
DOSSEG
.MODEL SMALL
.STACK 0100h
.DATA
.CODE
	MOV AX, @DATA
	MOV DS, AX

	MOV AH, 02h
	MOV CX, 05h
	B: MOV BX, CX
	MOV DL, 2Ah
	A: INT 21h
	LOOP A

	MOV DL, 0Ah
	INT 21h
	MOV DL, 0Dh
	INT 21h

	MOV CX, BX
	LOOP B

	MOV AX, 4C00h
	INT 21h
END