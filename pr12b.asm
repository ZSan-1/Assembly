TITLE pr12b.asm
DOSSEG
.MODEL SMALL
.STACK 0100h
.DATA
.CODE
	MOV AX, @DATA
	MOV DS, AX

	MOV AH, 02h
	MOV CX, 0Bh
	MOV DL, 41h
	A: INT 21h

	MOV BL, DL
	MOV DL, 0Ah
	INT 21h

	MOV DL, 08h
	INT 21h
	MOV DL, BL
	ADD DL, 03h
	LOOP A

	MOV AX, 4C00h
	INT 21h
END