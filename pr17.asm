TITLE pr17.asm
DOSSEG
.MODEL SMALL
.STACK 0100h
.DATA
	str1 DB "ARELLANO$"
.CODE
	MOV AX, @DATA
	MOV DS, AX

	MOV AX, 0600h
	MOV BH, 07h
	MOV CX, 0000h		;CLEAR SCREEN
	MOV DX, 184Fh
	INT 10h

	MOV AH, 02h
	MOV BH, 00h
	MOV DH, 0Ch		;ROW = 12 in DECIMAL
	MOV DL, 28h		;COL = 35 in DECIMAL
	INT 10h

	MOV AH, 09h
	MOV DX, OFFSET str1
	INT 21h

	MOV AX, 4C00h
	INT 21h
END