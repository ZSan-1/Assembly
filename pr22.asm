TITLE pr22.asm
DOSSEG
.MODEL SMALL
.STACK 0100h
.DATA
.CODE
	MOV AX, @DATA
	MOV DS, AX

	MOV AX, 0600h
	MOV BH, 07h			;CLEAR SCREEN
	MOV CX, 0000h		
	MOV DX, 184Fh
	INT 10h

	MOV AH, 02h			;SET CURSOR
	MOV BH, 00h
	MOV DH, 0Ch			;ROW 12
	MOV DL, 28h			;COL 40
	INT 10h

	MOV AH, 09h			;REQUEST CHARACTER DISPLAY

	MOV AL, 00h			;DO NOT ADVANCE CURSOR
	MOV BH, 00h			;PAGE 0
	MOV BL, 9Eh			;2(GREEN BG) 3(CYAN TC)
	MOV CX, 000Ah		;NUMBER OF CHARACTERS
	MOV AL, 41H
	INT 10h

	MOV AX, 4C00h
	INT 21h
END