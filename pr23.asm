TITLE pr23.asm
DOSSEG
.MODEL SMALL
.STACK 0100h
.DATA
	STR1 DB "ARELLANO$"
.CODE
	MOV AX, @DATA
	MOV DS, AX
	MOV ES, AX			;FOR STRING DISPLAY

	MOV AX, 0600h
	MOV BH, 07h			;CLEAR SCREEN
	MOV CX, 0000h		
	MOV DX, 184Fh
	INT 10h

	MOV AH, 13h			;REQ FOR CHAR W ATTRIBUTES
	MOV AL, 00h			;DO NOT ADV CURSOR
	MOV BH, 00h			;PAGE NUM 0
	MOV BL, 94h			;1 BLUE 4 RED PERO BLINKING SO PLUS 8 SA BLUE
	MOV BP, OFFSET STR1
	MOV CX, 0008h
	MOV DH, 0Ch			;ROW 12
	MOV DL, 28h			;COL 40
	INT 10h

	MOV AX, 4C00h
	INT 21h
END