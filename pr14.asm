TITLE pr14.asm
DOSSEG
.MODEL SMALL
.STACK 0100h
.DATA
.CODE
	MOV AX, @DATA
	MOV DS, AX

	MOV AH, 02h
	MOV CX, 01Ah
	MOV DL, 41h
	A: INT 21h

	MOV BL, DL
	ADD DL, 20h
	INT 21h

	MOV DL, 0Ah
	INT 21h
	MOV DL, 0Dh
	INT 21h
	MOV DL, BL
	INC DL
	LOOP A

	MOV AX, 4C00h
	INT 21h
END